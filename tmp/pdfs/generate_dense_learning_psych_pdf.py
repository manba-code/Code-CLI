def build_lines():
    lines = []
    for raw in CONTENT.strip().splitlines():
        raw = raw.strip()
        if not raw:
            lines.append(("", "MSYH", 5.8, 2.2))
            continue
        if raw.startswith("# "):
            text = raw[2:]
            lines.append((text, "MSYHB", 11.0, 13.5))
        elif raw.startswith("## "):
            text = raw[3:]
            lines.append((text, "MSYHB", 7.6, 9.4))
        else:
            lines.append((raw, "MSYH", 5.65, 6.85))
    return lines


def draw_flow(c, items):
    width, height = A4
    mx, my = 18, 18
    top_extra = 14
    footer_h = 10
    gap = 8
    cols = 3
    col_w = (width - 2 * mx - gap * (cols - 1)) / cols
    x_positions = [mx + i * (col_w + gap) for i in range(cols)]
    max_pages = 6
    page = 1
    col = 0
    x = x_positions[col]
    y = height - my - top_extra

    def footer():
        c.setFont("MSYH", 5.4)
        c.setFillColorRGB(0.38, 0.38, 0.38)
        c.drawCentredString(width / 2, my - 4, f"期末复习讲义-学习心理学 6页高密考点版 | 第 {page}/6 页")

    for text, font, size, leading in items:
        wrapped = [""] if not text else wrap(text, font, size, col_w)
        needed = len(wrapped) * leading
        if y - needed < my + footer_h:
            col += 1
            if col >= cols:
                footer()
                c.showPage()
                page += 1
                col = 0
                if page > max_pages:
                    return page - 1, False
            x = x_positions[col]
            y = height - my - top_extra
        for line in wrapped:
            if line:
                c.setFont(font, size)
                c.setFillColorRGB(0, 0, 0)
                c.drawString(x, y, line)
            y -= leading
    footer()
    while page < max_pages:
        c.showPage()
        page += 1
        footer()
    return page, True


