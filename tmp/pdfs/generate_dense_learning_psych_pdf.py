def wrap(text, font, size, width):
    out = []
    line = ""
    for ch in text:
        if ch == "\n":
            if line:
                out.append(line)
                line = ""
            out.append("")
            continue
        if pdfmetrics.stringWidth(line + ch, font, size) <= width:
            line += ch
        else:
            if line:
                out.append(line)
            line = ch
    if line:
        out.append(line)
    return out


