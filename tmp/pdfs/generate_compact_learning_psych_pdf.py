def draw_page(c, page_text, page_no):
    width, height = A4
    margin_x = 24
    margin_y = 22
    gap = 14
    col_w = (width - 2 * margin_x - gap) / 2
    top = height - margin_y - 22
    bottom = margin_y + 18
    title = page_text.split("\n", 1)[0]
    body = page_text.split("\n", 1)[1].strip()

    c.setFont("MSYHB", 12)
    c.drawString(margin_x, height - margin_y - 6, title)
    c.setLineWidth(0.4)
    c.line(margin_x, height - margin_y - 12, width - margin_x, height - margin_y - 12)

    font_size = 7.05
    leading = 8.4
    heading_size = 8.0
    x_positions = [margin_x, margin_x + col_w + gap]
    paragraphs = body.split("\n")
    draw_lines = []
    for para in paragraphs:
        if not para.strip():
            draw_lines.append(("", "MSYH", font_size, leading * 0.45))
            continue
        is_heading = len(para) < 28 and ("：" not in para) and not para.startswith(("应用", "关键词", "答题", "比较", "综合", "速查", "模板", "必背"))
        font = "MSYHB" if is_heading else "MSYH"
        size = heading_size if is_heading else font_size
        lines = wrap(para, font, size, col_w)
        for line in lines:
            draw_lines.append((line, font, size, leading))
        draw_lines.append(("", "MSYH", font_size, leading * 0.18))

    total_height = sum(item[3] for item in draw_lines)
    target = total_height / 2
    running = 0
    split_at = len(draw_lines)
    for i, item in enumerate(draw_lines):
        running += item[3]
        if running >= target:
            split_at = i + 1
            break

    for col, col_lines in enumerate((draw_lines[:split_at], draw_lines[split_at:])):
        x = x_positions[col]
        y = top
        for line, font, size, step in col_lines:
            if y < bottom:
                c.setFillColorRGB(0.75, 0, 0)
                c.setFont("MSYHB", 7)
                c.drawRightString(width - margin_x, bottom - 4, "本页内容略有溢出，请通知我再压缩")
                return
            if line:
                c.setFont(font, size)
                c.setFillColorRGB(0, 0, 0)
                c.drawString(x, y, line)
            y -= step

    c.setFont("MSYH", 6.5)
    c.setFillColorRGB(0.35, 0.35, 0.35)
    c.drawCentredString(width / 2, margin_y - 2, f"期末复习讲义-学习心理学 6页速查版  |  第 {page_no}/6 页")


def main():
    register_fonts()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    c = canvas.Canvas(str(OUT), pagesize=A4)
    c.setTitle("期末复习讲义-学习心理学-6页速查版")
    for i, page in enumerate(pages, 1):
        draw_page(c, page, i)
        c.showPage()
    c.save()
    print(OUT)


if __name__ == "__main__":
    main()
