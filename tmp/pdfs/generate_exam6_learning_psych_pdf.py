def render_page(c, text, page_no):
    width, height = A4
    mx, my = 18, 18
    gap = 10
    col_w = (width - 2 * mx - gap) / 2
    top = height - my - 26
    bottom = my + 13
    x_positions = [mx, mx + col_w + gap]
    text = text + "\n" + SUPPLEMENTS[page_no - 1]
    title, body = text.split("\n", 1)

    c.setFont("MSYHB", 11.5)
    c.drawString(mx, height - my - 5, title)
    c.setLineWidth(0.35)
    c.line(mx, height - my - 11, width - mx, height - my - 11)

    items = []
    for para in body.strip().splitlines():
        para = para.strip()
        if not para:
            items.append(("", "MSYH", 12.0, 4.0))
        elif para.startswith("【"):
            items.append((para, "MSYH", 12.0, 13.4))
        else:
            items.append((para, "MSYH", 12.0, 13.4))

    # Wrap all lines, then split by total rendered height so both columns are used.
    rendered = []
    for para, font, size, leading in items:
        for line in ([""] if not para else wrap(para, font, size, col_w)):
            rendered.append((line, font, size, leading))
        rendered.append(("", "MSYH", 12.0, 1.5))

    half = sum(line[3] for line in rendered) / 2
    running, split = 0, len(rendered)
    for i, line in enumerate(rendered):
        running += line[3]
        if running >= half:
            split = i + 1
            break

    overflow = False
    for col, lines in enumerate((rendered[:split], rendered[split:])):
        x, y = x_positions[col], top
        for line, font, size, leading in lines:
            if y < bottom:
                overflow = True
                break
            if line:
                c.setFont(font, size)
                c.drawString(x, y, line)
            y -= leading
    c.setFont("MSYH", 5.6)
    c.setFillColorRGB(0.35, 0.35, 0.35)
    c.drawCentredString(width / 2, my - 4, f"期末复习讲义-学习心理学 6页满版考点版 | 第 {page_no}/6 页")
    c.setFillColorRGB(0, 0, 0)
    if overflow:
        c.setFont("MSYHB", 6)
        c.setFillColorRGB(0.75, 0, 0)
        c.drawRightString(width - mx, my + 2, "本页内容溢出，请继续压缩")
        c.setFillColorRGB(0, 0, 0)
    return not overflow


