def wrap(text, font, size, width):
    lines, line = [], ""
    for ch in text:
        if ch == "\n":
            if line:
                lines.append(line)
                line = ""
            lines.append("")
            continue
        if pdfmetrics.stringWidth(line + ch, font, size) <= width:
            line += ch
        else:
            if line:
                lines.append(line)
            line = ch
    if line:
        lines.append(line)
    return lines


